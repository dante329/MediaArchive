#!/usr/bin/env node
/**
 * 从常驻下载器 Chrome（CDP）导出全部 Cookie 为 Netscape cookies.txt，供 yt-dlp 使用。
 * 用法: node export_cookies.js [port] [out]
 *
 * CDP 的超时/断连处理见 tools/cdp.js。
 */
const fs = require('fs');
const os = require('os');
const path = require('path');
const cdp = require('./cdp');

const PORT = process.argv[2] || '9222';
const OUT = process.argv[3] || path.join(os.homedir(), '.media-archive', 'cookies.txt');

function toNetscape(cookies) {
  const seen = new Set();
  const lines = ['# Netscape HTTP Cookie File', '# Generated by MediaArchive', ''];
  for (const c of cookies) {
    const domain = c.domain || '';
    const p = c.path || '/';
    const name = String(c.name || '');
    const value = String(c.value == null ? '' : c.value).replace(/[\t\r\n]/g, ' ');
    if (!domain || !name) continue;
    const key = `${domain}\t${p}\t${name}`;
    if (seen.has(key)) continue;
    seen.add(key);
    const flag = domain.startsWith('.') ? 'TRUE' : 'FALSE';
    const secure = c.secure ? 'TRUE' : 'FALSE';
    const expiry = Math.floor(c.expires && c.expires > 0 ? c.expires : 0);
    lines.push([domain, flag, p, secure, expiry, name, value].join('\t'));
  }
  return { text: lines.join('\n') + '\n', count: seen.size };
}

(async () => {
  let list;
  try {
    list = await cdp.listTabs(PORT);
  } catch (e) {
    throw new Error(`连不上 Chrome 调试端口 ${PORT}（常驻 Chrome 没起来？）：${e.message}`);
  }
  const page = (list || []).find(t => t.type === 'page' && t.webSocketDebuggerUrl) ||
    (list || []).find(t => t.webSocketDebuggerUrl);
  if (!page) throw new Error('Chrome 里没有可连接的页面');

  // 借已有标签页读 cookie，读完只断连接、不关别人的页面
  const client = await cdp.connect(page.webSocketDebuggerUrl, { cmdTimeout: 30000, openTimeout: 15000 });
  let cookies = [];
  try {
    await client.send('Network.enable').catch(() => {});
    let m = await client.send('Network.getAllCookies').catch(() => null);
    cookies = (m && m.result && m.result.cookies) || [];
    if (!cookies.length) {
      // 新版 Chrome 把 cookie 挪到了 Storage 域
      m = await client.send('Storage.getCookies').catch(() => null);
      cookies = (m && m.result && m.result.cookies) || [];
    }
  } finally {
    client.close();
  }
  if (!cookies.length) throw new Error('没有导出到任何 Cookie（Chrome 里可能还没有登录态）');

  const { text, count } = toNetscape(cookies);
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, text, 'utf8');
  try { fs.chmodSync(OUT, 0o600); } catch (e) {}
  console.log(`exported ${count} cookies -> ${OUT}`);
  cdp.finish(0);
})().catch(e => {
  console.error('export failed:', (e && e.message) || String(e));
  cdp.finish(1);
});
