#!/usr/bin/env node
/**
 * 从常驻下载器 Chrome（CDP）导出全部 Cookie 为 Netscape cookies.txt，供 yt-dlp 使用。
 * 用法: node export_cookies.js [port] [out]
 */
const fs = require('fs');
const os = require('os');
const path = require('path');
const PORT = process.argv[2] || '9222';
const OUT = process.argv[3] || path.join(os.homedir(), '.media-archive', 'cookies.txt');
const HTTP = `http://127.0.0.1:${PORT}`;

(async () => {
  const list = await (await fetch(`${HTTP}/json/list`)).json();
  const page = list.find(t => t.type === 'page' && t.webSocketDebuggerUrl) || list.find(t => t.webSocketDebuggerUrl);
  if (!page) throw new Error('Chrome 里没有可连接的页面');
  const ws = new WebSocket(page.webSocketDebuggerUrl);
  let id = 1;
  const pending = new Map();
  ws.addEventListener('message', ev => {
    const m = JSON.parse(ev.data);
    if (m.id && pending.has(m.id)) { pending.get(m.id)(m); pending.delete(m.id); }
  });
  await new Promise(r => ws.addEventListener('open', r));
  const send = (method, params = {}) => new Promise(res => {
    const i = id++;
    pending.set(i, res);
    ws.send(JSON.stringify({ id: i, method, params }));
  });
  await send('Network.enable');
  const res = await send('Network.getAllCookies');
  const cookies = (res.result && res.result.cookies) || [];
  const seen = new Set();
  const lines = ['# Netscape HTTP Cookie File', '# Generated by MediaArchive', ''];
  for (const c of cookies) {
    let domain = c.domain || '';
    let p = c.path || '/';
    let name = String(c.name || '');
    let value = String(c.value == null ? '' : c.value).replace(/[\t\r\n]/g, ' ');
    if (!domain || !name) continue;
    const key = `${domain}\t${p}\t${name}`;
    if (seen.has(key)) continue;
    seen.add(key);
    const flag = domain.startsWith('.') ? 'TRUE' : 'FALSE';
    const secure = c.secure ? 'TRUE' : 'FALSE';
    const expiry = Math.floor(c.expires && c.expires > 0 ? c.expires : 0);
    lines.push([domain, flag, p, secure, expiry, name, value].join('\t'));
  }
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, lines.join('\n') + '\n', 'utf8');
  try { fs.chmodSync(OUT, 0o600); } catch (e) {}
  console.log(`exported ${seen.size} cookies -> ${OUT}`);
  ws.close();
  process.exit(0);
})().catch(e => { console.error('export failed:', e.message); process.exit(1); });
